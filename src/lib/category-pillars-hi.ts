/**
 * Hindi category-pillar registry — Devanagari content for /hi/category/{slug}.
 *
 * The English-side `categoryPillars` (lib/category-pillars.ts) carries
 * 800-900 words of long-form pillar content per category. The Hindi side
 * is intentionally tighter (~300-400 words per pillar) for a few reasons:
 *   1. Hindi search results favour focused, scannable answers — long
 *      machine-translated walls of text rank poorly and look unnatural.
 *   2. Indian users on the Hindi side are predominantly mobile, so we
 *      keep paragraphs short and cap each section.
 *   3. Hindi content needs human review before scaling up; this size is
 *      what we can hand-write authentically right now without leaning
 *      on auto-translation.
 *
 * Schema is deliberately a subset of the English pillar — `whatIs`,
 * `useCases`, `indianContext`, and `pillarFaqs` only. The Hindi
 * `/hi/category/{slug}` page renders these plus the tools grid (already
 * shown on the Hindi homepage as a flat list — pillar pages are the
 * topic-cluster organisation that Hindi search couldn't access before).
 *
 * Tool names in headings stay in Latin script (e.g. "EMI कैलकुलेटर")
 * because that's how Indian users actually search for them — pure
 * Devanagari "ईएमआई" gets a fraction of the search volume.
 */

export interface CategoryPillarHi {
  /** 80-150 word Hindi paragraph: what this category is and who it serves. */
  whatIs: string;
  /** 3-4 use-case bullets, ~15-25 Hindi words each. */
  useCases: string[];
  /** 60-100 word paragraph on India-specific defaults / regulations / pricing. */
  indianContext: string;
  /** 3-4 question/answer pairs in Hindi, ~30-60 Hindi words per answer. */
  pillarFaqs: { q: string; a: string }[];
  /**
   * Devanagari category name shown to Hindi users — overrides the English
   * `cat.name` from `tools.ts` everywhere on `/hi/category/{slug}` (H1,
   * meta description, JSON-LD CollectionPage / ItemList / WebPage `name`,
   * breadcrumb labels). Hand-written per category. Where the term is a
   * loanword Indian users search for in Latin form ("PDF", "EMI", "GST",
   * "रियल एस्टेट"), Devanagari transliteration is preferred over a
   * forced Sanskritised translation that no one searches for.
   * Phase 6 Round 2 — Task A.
   */
  name: string;
}

