#!/usr/bin/env node
/**
 * scripts/check-rate-staleness.mjs
 *
 * Project Trust · Phase 4 — Weekly Rate Review checker.
 *
 * Reads `src/data/rates.ts` and produces a markdown report listing
 * every rate that has aged past its `reviewIntervalDays` window.
 * The GitHub Action `rate-review.yml` runs this every Monday at
 * 9 AM IST (3:30 AM UTC) and uses the output to open / update a
 * GitHub Issue. GitHub then emails the repo owner (Rakesh) so a
 * Monday-morning email lands automatically — no SMTP secrets, no
 * external service, no ongoing cost.
 *
 * The script parses rates.ts with a deliberate regex (NOT eval / NOT
 * import — keeps the runtime clean and avoids needing a transpiler in
 * the GitHub Action). Every rate entry must include:
 *   - lastVerified:         "YYYY-MM-DD"
 *   - reviewIntervalDays:   number
 *   - source:               URL
 * The variable name (e.g. PPF, EPF, SCSS) becomes the report label.
 *
 * Usage:
 *   node scripts/check-rate-staleness.mjs
 *
 * Exits 0 always (so the workflow can decide what to do based on the
 * `overdueCount` line in stdout). Output is a Markdown document
 * suitable for an Issue body.
 */

import { readFileSync } from "node:fs";
import { fileURLToPath } from "node:url";
import { dirname, join } from "node:path";

const __filename = fileURLToPath(import.meta.url);
const __dirname = dirname(__filename);
const RATES_PATH = join(__dirname, "..", "src", "data", "rates.ts");

const source = readFileSync(RATES_PATH, "utf8");

// Extract every `export const NAME: RateEntry... = { ... };` block.
// Capture: the variable name, the inner object body, and within it the
// lastVerified / reviewIntervalDays / source fields.
const blockRe =
  /export\s+const\s+([A-Z][A-Z0-9_]*)\s*:\s*RateEntry[^=]*=\s*\{([\s\S]*?)\n\}\s*;/g;
const fieldRe = (key) =>
  new RegExp(`${key}\\s*:\\s*("([^"\\n]*)"|([0-9]+(?:\\.[0-9]+)?))`);

const today = new Date();
const todayIso = today.toISOString().slice(0, 10);

const entries = [];
let m;
while ((m = blockRe.exec(source)) !== null) {
  const name = m[1];
  const body = m[2];
  const lvMatch = body.match(fieldRe("lastVerified"));
  const rdMatch = body.match(fieldRe("reviewIntervalDays"));
  const srcMatch = body.match(fieldRe("source"));
  if (!lvMatch || !rdMatch || !srcMatch) continue;
  const lastVerified = lvMatch[2];
  const reviewIntervalDays = Number(rdMatch[3]);
  const sourceUrl = srcMatch[2];
  const lv = new Date(lastVerified);
  const days = Math.floor((today.getTime() - lv.getTime()) / 86_400_000);
  const overdue = days > reviewIntervalDays;
  const veryOverdue = days > reviewIntervalDays + 60;
  entries.push({
    name,
    lastVerified,
    reviewIntervalDays,
    daysOld: days,
    overdue,
    veryOverdue,
    sourceUrl,
  });
}

if (entries.length === 0) {
  console.error("⚠️  No RateEntry blocks parsed from rates.ts — check the regex.");
  process.exit(1);
}

const overdue = entries.filter((e) => e.overdue);
const dueSoon = entries.filter(
  (e) => !e.overdue && e.reviewIntervalDays - (e.reviewIntervalDays - e.daysOld) >= e.reviewIntervalDays - 14
);

// Build the markdown report.
let md = `# Weekly Rate Review — ${todayIso}\n\n`;
md += `_Auto-generated by SabTools Project Trust on every Monday._\n\n`;
md += `**${overdue.length}** rate${overdue.length === 1 ? "" : "s"} overdue · `;
md += `**${entries.length}** total entries tracked.\n\n`;

if (overdue.length === 0) {
  md += `✅ All rates are within their review window. No action needed this week.\n\n`;
} else {
  md += `## 🚨 Overdue rates — verify on the source link, reply here with the values\n\n`;
  md += `| Rate | Last verified | Days old | Review every | Source |\n`;
  md += `|---|---|---:|---:|---|\n`;
  for (const e of overdue.sort((a, b) => b.daysOld - a.daysOld)) {
    const flag = e.veryOverdue ? "🔴" : "🟡";
    md += `| ${flag} **${e.name}** | ${e.lastVerified} | ${e.daysOld}d | ${e.reviewIntervalDays}d | [Verify](${e.sourceUrl}) |\n`;
  }
  md += `\n### How to update\n\n`;
  md += `1. Click each "Verify" link, glance at the current rate on the official Government page.\n`;
  md += `2. Reply to this issue with each rate: \`PPF: 7.1 confirmed\` or \`PPF: 7.3 new\` (one line per rate).\n`;
  md += `3. Or update \`src/data/rates.ts\` directly — change the \`value\` if revised, and update \`lastVerified\` to today's date.\n`;
  md += `4. Once you've reviewed all of them, close this issue. Next Monday's check will reopen it if anything has gone overdue again.\n\n`;
}

if (dueSoon.length > 0) {
  md += `\n## 📅 Due for review within 2 weeks (no action yet)\n\n`;
  md += `<details><summary>Show ${dueSoon.length} entries</summary>\n\n`;
  md += `| Rate | Last verified | Days old | Review every |\n`;
  md += `|---|---|---:|---:|\n`;
  for (const e of dueSoon) {
    md += `| ${e.name} | ${e.lastVerified} | ${e.daysOld}d | ${e.reviewIntervalDays}d |\n`;
  }
  md += `\n</details>\n`;
}

md += `\n---\n\n`;
md += `<sub>Generated by \`scripts/check-rate-staleness.mjs\` · `;
md += `Project Trust Phase 4 weekly review · `;
md += `[Plan doc](./PROJECT_TRUST_PLAN.md) · `;
md += `${entries.length} rates tracked across ${new Set(entries.map((e) => new URL(e.sourceUrl).hostname)).size} sources.</sub>\n`;

// Output the report on stdout — workflow consumes this.
console.log(md);

// Send machine-readable summary line on stderr so the workflow can branch.
console.error(
  `overdueCount=${overdue.length} totalEntries=${entries.length}`
);
